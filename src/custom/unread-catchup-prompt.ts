export function buildDefaultCatchupPrompt(): string {
  return [
    "你刚刚按轮询节奏看了一眼这个QQ群过去一会儿的未读消息。",
    "先在心里判断未读消息里有几个话题：",
    "- 如果只有单个话题：结合上下文，像群里的真人成员一样自然接一句自己的发言。",
    "- 如果有多个话题：为每个话题挑一个最有代表性或最有爆点发言的成员，用 <@member_openid> 提到对方，再结合对应话题发表一句自然发言。",
    "只发最终群聊消息，不要输出话题数量、分析过程或逐条总结。",
    "不要提到任务、定时器、轮询、机制、系统提示或自己在查看历史。",
    "不要使用工具，除非群友明确求助。",
  ].join("");
}
